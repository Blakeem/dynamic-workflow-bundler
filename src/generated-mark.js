// Each mark must stay the start of the third line of every later version's document, since dwfb map and
// dwfb snapshot read documents that an earlier version wrote before they replace them.
export const FLOW_MAP_MARK = 'Generated by `dwfb map`.';
export const PROMPT_SNAPSHOT_MARK = 'Generated by `dwfb snapshot`.';
// A document opens with its title line and a blank line. A hand-written file, such as a README that quotes a
// document, can hold the mark on a later line.
const MARK_LINE_INDEX = 2;

/**
 * Reads no disk.
 * @param {string} text The text of a file.
 * @param {string} mark
 * @returns {boolean} True when the third line of the text starts with the mark.
 */
export function hasGeneratedMark(text, mark) {
  const lines = text.split('\n', MARK_LINE_INDEX + 1);

  return lines.length > MARK_LINE_INDEX && lines[MARK_LINE_INDEX].startsWith(mark);
}
