import { escapeCell } from './escape-cell.js';
import { formatUnwritableCharacters } from './format-hidden-characters.js';
import { FLOW_MAP_MARK } from './generated-mark.js';

/** @typedef {import('./build-flow-graph.js').FlowGraph} FlowGraph */
/** @typedef {import('./build-flow-graph.js').FlowEdge} FlowEdge */
/** @typedef {import('./build-flow-graph.js').AgentNode} AgentNode */
/** @typedef {import('./build-flow-graph.js').EndNode} EndNode */

const GENERATED_LINES = [
  `${FLOW_MAP_MARK} Do not edit this file by hand.`,
  'Each node and edge below was reached by a scenario, so the diagram shows what the script does in a simulation.',
].join('\n');
// The spacing and the caption budget of the reference generator, which the oracle documents of tests/fixtures/flow-map/ hold.
const INIT_LINE = '%%{init: {"flowchart": {"nodeSpacing": 80, "rankSpacing": 200}}}%%';
const WHEN_BUDGET = 70;
const MIN_WHEN_ROOM = 8;
const START_LINE = '  S0(["args"])';
const WHEN_SEPARATOR = ' · ';
const NEXT_ITEM_CAPTION = 'next item';
const MIN_BOX_NODES = 2;
const EDGES_NOTE = 'The thick edge with no caption of each pair above is the step to the next item.';
const WHITE_SPACE_RUN = /\s+/g;

/**
 * Writes the flow map of a script as one Markdown document with one Mermaid diagram, and reads no disk and
 * prints nothing.
 * @param {string} title The `name` of the script's meta object.
 * @param {FlowGraph} graph
 * @returns {string} The document, which ends with one line end.
 */
export function formatFlowMap(title, graph) {
  const markers = assignMarkers(graph.edges);
  const nodeLabels = new Map(graph.nodes.map((node) => [node.id, node.label]));
  const loopRows = [];
  const edgeRows = [];
  const parts = [`# ${escapeCell(title)} flow map`, GENERATED_LINES, formatDiagram(graph, markers)];

  // Only a back edge holds a marker, and no back edge leaves the start, which has no node label.
  graph.edges.forEach((edge, index) => {
    const marker = markers[index];
    if (marker === '') return;
    const whens = escapeCell(edge.whens.join(WHEN_SEPARATOR));
    const fromLabel = escapeCell(/** @type {string} */ (nodeLabels.get(edge.from)));
    if (marker.startsWith('L')) loopRows.push(`| ${marker} | ${fromLabel} | ${whens} |`);
    else edgeRows.push(`| ${marker} | ${fromLabel} | ${escapeCell(/** @type {string} */ (nodeLabels.get(edge.to)))} | ${whens} |`);
  });

  parts.push(formatSection('## Phases', '| Phase | What happens |', graph.phases.filter((phase) => phase.nodes.length > 0).map((phase) => `| ${escapeCell(phase.title)} | ${escapeCell(phase.detail)} |`)));
  if (loopRows.length > 0) parts.push(formatSection('## Loops', '| Loop | Agent | Repeats while |', loopRows));
  if (edgeRows.length > 0) parts.push(formatSection('## Edges', '| Edge | From | To | Taken when |', edgeRows), EDGES_NOTE);
  parts.push(formatSection('## End states', '| End state | Reached when | Source |', graph.nodes.filter(isEndNode).map(formatEndRow)));

  return `${parts.join('\n\n')}\n`;
}

/**
 * Gives each back edge from a node to itself a loop marker `L<n>`, then each other back edge whose pair of
 * nodes also holds a next-item edge an edge marker `E<n>`, each numbered in edge order.
 * @param {FlowEdge[]} edges
 * @returns {string[]} The marker of each edge, or '' for an edge with none.
 */
function assignMarkers(edges) {
  const markers = edges.map(() => '');
  const nextItemPairs = new Set(edges.filter((edge) => edge.nextItem).map(formatPairKey));
  let loopCount = 0;
  let edgeCount = 0;

  edges.forEach((edge, index) => {
    if (edge.back && edge.from === edge.to) {
      loopCount += 1;
      markers[index] = `L${loopCount}`;
    }
  });
  edges.forEach((edge, index) => {
    if (edge.back && markers[index] === '' && nextItemPairs.has(formatPairKey(edge))) {
      edgeCount += 1;
      markers[index] = `E${edgeCount}`;
    }
  });

  return markers;
}

/**
 * @param {FlowGraph} graph
 * @param {string[]} markers
 * @returns {string} The fenced Mermaid block.
 */
function formatDiagram(graph, markers) {
  const boxes = graph.phases.filter((phase) => phase.nodes.length >= MIN_BOX_NODES);
  const boxedIds = new Set(boxes.flatMap((phase) => phase.nodes));
  const nodesById = new Map(graph.nodes.map((node) => [node.id, node]));
  const markedPairs = new Set(graph.edges.filter((_, index) => markers[index].startsWith('E')).map(formatPairKey));
  const lines = ['```mermaid', INIT_LINE, 'flowchart TD', START_LINE];

  for (const phase of boxes) {
    lines.push(`  subgraph ${phase.id}["${escapeMermaid(phase.title)}"]`);
    for (const id of phase.nodes) lines.push(`    ${formatNodeLine(/** @type {AgentNode | EndNode} */ (nodesById.get(id)))}`);
    lines.push('  end');
  }
  for (const node of graph.nodes) {
    if (!boxedIds.has(node.id)) lines.push(`  ${formatNodeLine(node)}`);
  }
  graph.edges.forEach((edge, index) => lines.push(`  ${formatEdgeLine(edge, markers[index], markedPairs)}`));
  lines.push('```');

  return lines.join('\n');
}

/**
 * @param {AgentNode | EndNode} node
 * @returns {string} Such as `a1["work · sonnet<br/>Fixture<br/>×2 concurrent"]`, with no indent.
 */
function formatNodeLine(node) {
  if (node.kind === 'end') return `${node.id}(["${escapeMermaid(node.label)}"])`;
  if (node.kind === 'throw') return `${node.id}[/"${escapeMermaid(node.label)}"/]`;

  const nameText = escapeMermaid(node.model === '' ? node.label : `${node.label}${WHEN_SEPARATOR}${node.model}`);
  // A phase named after its role adds nothing to the role's name.
  const phaseText = node.phase !== '' && node.phase.toLowerCase() !== node.label.toLowerCase() ? `<br/>${escapeMermaid(node.phase)}` : '';
  const concurrencyText = node.concurrency > 1 ? `<br/>×${node.concurrency} concurrent` : '';

  return `${node.id}["${nameText}${phaseText}${concurrencyText}"]`;
}

/**
 * @param {FlowEdge} edge
 * @param {string} marker The edge's marker, or ''.
 * @param {Set<string>} markedPairs The pairs of nodes whose back edge holds an edge marker.
 * @returns {string} One edge line of the diagram, with no indent.
 */
function formatEdgeLine(edge, marker, markedPairs) {
  const { from, to, repeat } = edge;

  // The marked back edge of the pair carries the caption, so its next-item edge needs none.
  if (edge.nextItem && markedPairs.has(formatPairKey(edge))) return `${from} ==> ${to}`;
  if (edge.nextItem) return `${from} ==>|"${NEXT_ITEM_CAPTION}"| ${to}`;
  if (edge.back && marker !== '') return `${from} -.->|"${marker}${repeat > 1 ? ` ×${repeat}` : ''}"| ${to}`;
  if (edge.back) {
    const repeatText = repeat > 1 ? ` (×${repeat})` : '';
    return `${from} -.->|"${escapeMermaid(formatWhenCaption(edge.whens, repeatText.length))}${repeatText}"| ${to}`;
  }
  return `${from} --> ${to}`;
}

/**
 * Joins as many conditions as fit in the caption budget, and counts the rest as `+<k> more`. One condition is
 * kept whole, whatever its length.
 * @param {string[]} whens
 * @param {number} reserve The characters the caption holds after the conditions.
 * @returns {string}
 */
function formatWhenCaption(whens, reserve) {
  const room = Math.max(MIN_WHEN_ROOM, WHEN_BUDGET - reserve);
  let count = whens.length;

  while (count > 1 && formatWhenList(whens, count).length > room) count -= 1;

  return formatWhenList(whens, count);
}

/**
 * @param {string[]} whens
 * @param {number} count The conditions to name.
 * @returns {string}
 */
function formatWhenList(whens, count) {
  const restCount = whens.length - count;
  const named = whens.slice(0, count);

  return restCount > 0 ? [...named, `+${restCount} more`].join(WHEN_SEPARATOR) : named.join(WHEN_SEPARATOR);
}

/**
 * @param {string} heading
 * @param {string} header The table's header row.
 * @param {string[]} rows
 * @returns {string}
 */
function formatSection(heading, header, rows) {
  const columnCount = header.split('|').length - 2;
  const divider = `|${'---|'.repeat(columnCount)}`;

  return [heading, '', header, divider, ...rows].join('\n');
}

/**
 * @param {AgentNode | EndNode} node
 * @returns {node is EndNode}
 */
function isEndNode(node) {
  return node.kind !== 'agent';
}

/**
 * @param {EndNode} node
 * @returns {string}
 */
function formatEndRow(node) {
  const source = node.kind === 'throw' ? `throw (line ${node.line})` : node.source;

  return `| ${escapeCell(node.label)} | ${escapeCell(node.whens.join(WHEN_SEPARATOR))} | ${source} |`;
}

/**
 * @param {{ from: string, to: string }} edge
 * @returns {string}
 */
function formatPairKey({ from, to }) {
  return `${from}->${to}`;
}

/**
 * Mermaid ends a quoted text at `"` and an edge caption at `|`, reads a backtick right after the opening `"` as
 * the start of a markdown string, drops the text between `<` and `>` as an HTML tag, and decodes each `#<code>;`
 * as an entity code and each `&<name>;` as an HTML entity, and renders the text between `$$` and `$$` as KaTeX
 * math, as mermaid 11.4.1 renders it. Mermaid swaps each `#<code>;` for a placeholder before it looks for `$$`.
 * A lone surrogate and a U+0000 are written as their escape, such as \u{D83D}.
 * @param {string} text
 * @returns {string}
 */
function escapeMermaid(text) {
  return formatUnwritableCharacters(text).replace(WHITE_SPACE_RUN, ' ').trim().replaceAll('#', '#35;').replaceAll('$', '#36;').replaceAll('`', '#96;').replaceAll('&', '#38;').replaceAll('"', '#quot;').replaceAll('|', '#124;').replaceAll('<', '#lt;').replaceAll('>', '#gt;');
}
