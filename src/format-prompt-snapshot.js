import { escapeCell } from './escape-cell.js';
import { formatHiddenCharacters, formatUnwritableCharacters } from './format-hidden-characters.js';
import { PROMPT_SNAPSHOT_MARK } from './generated-mark.js';

/** @typedef {import('./build-prompt-snapshot.js').PromptVariant} PromptVariant */

const GENERATED_LINES = [
  `${PROMPT_SNAPSHOT_MARK} Do not edit this file by hand.`,
  'Each entry below is one distinct prompt that a role receives, with the scenario that first sent it.',
].join('\n');
const TABLE_HEAD = ['| Role | Variant | Schema | Characters | First scenario |', '|---|---|---|---|---|'];
const MIN_FENCE_LENGTH = 4;
const TILDE_RUN = /~+/g;
const BACKTICK_RUN = /`+/g;
const ALL_SPACES = /^ +$/;

/**
 * Writes the prompt snapshot of a script as one Markdown document, and reads no disk and prints nothing.
 * @param {string} title The `name` of the script's meta object.
 * @param {PromptVariant[]} variants As snapshot() gives them.
 * @returns {string} The document, which ends with one line end.
 */
export function formatPromptSnapshot(title, variants) {
  const rows = variants.map(({ role, number, schemaNumber, characters, scenario }) => `| ${formatName(role)} | ${number} | ${schemaNumber} | ${characters} | ${formatName(scenario)} |`);
  const parts = [`# ${formatName(title)} prompt snapshot`, GENERATED_LINES, [...TABLE_HEAD, ...rows].join('\n'), ...variants.map(formatVariant)];

  return `${parts.join('\n\n')}\n`;
}

/**
 * @param {PromptVariant} variant
 * @returns {string} The variant's section, with no line end after its last fence.
 */
function formatVariant({ role, number, schemaNumber, scenario, label, prompt, schema }) {
  const scenarioText = `the scenario "${formatName(scenario)}"`;
  const callLine = formatCallLine(label, scenarioText);

  // `JSON.stringify` already escapes each lone surrogate and each U+0000 of the schema text.
  return [`## ${formatName(role)}, variant ${number}, schema ${schemaNumber}`, callLine, formatFence('text', formatUnwritableCharacters(prompt)), formatFence('json', JSON.stringify(schema, null, 2))].join('\n\n');
}

/**
 * Markdown has no empty code span, so the empty label is written in words.
 * @param {string | null} label
 * @param {string} scenarioText
 * @returns {string}
 */
function formatCallLine(label, scenarioText) {
  if (label === null) return `A call with no label in ${scenarioText}`;
  if (label === '') return `A call with the empty label in ${scenarioText}`;
  return `${formatCodeSpan(formatHiddenCharacters(label))} in ${scenarioText}`;
}

/**
 * @param {string} name A title, a role or a scenario name.
 * @returns {string} The name on one line, with each hidden character escaped, as Markdown shows it.
 */
function formatName(name) {
  return escapeCell(formatHiddenCharacters(name));
}

/**
 * A fence longer than each run of `~` in its text cannot be closed by a line of that text.
 * @param {string} infoWord
 * @param {string} text
 * @returns {string}
 */
function formatFence(infoWord, text) {
  const fence = '~'.repeat(Math.max(MIN_FENCE_LENGTH, findLongestRun(text, TILDE_RUN) + 1));

  return `${fence}${infoWord}\n${text}\n${fence}`;
}

/**
 * A code span ends at the first backtick run as long as its opening run. A renderer strips one space from each
 * end of content that starts and ends with a space and is not all spaces, so one added space keeps a backtick
 * at an end of the label apart from the delimiter, and keeps a space at both ends of the label.
 * @param {string} label A label with no line end, and not empty.
 * @returns {string}
 */
function formatCodeSpan(label) {
  const delimiter = '`'.repeat(findLongestRun(label, BACKTICK_RUN) + 1);
  const hasBacktickEnd = label.startsWith('`') || label.endsWith('`');
  const hasStrippedSpaces = label.startsWith(' ') && label.endsWith(' ') && !ALL_SPACES.test(label);
  const padding = hasBacktickEnd || hasStrippedSpaces ? ' ' : '';

  return `${delimiter}${padding}${label}${padding}${delimiter}`;
}

/**
 * @param {string} text
 * @param {RegExp} runPattern A global pattern of a run of one character.
 * @returns {number} The length of the longest match, or 0 for none.
 */
function findLongestRun(text, runPattern) {
  return Array.from(text.matchAll(runPattern)).reduce((longest, match) => Math.max(longest, match[0].length), 0);
}
