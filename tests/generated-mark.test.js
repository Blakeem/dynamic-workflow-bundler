import assert from 'node:assert/strict';
import { describe, it } from 'node:test';
import { formatFlowMap } from '../src/format-flow-map.js';
import { formatPromptSnapshot } from '../src/format-prompt-snapshot.js';
import { FLOW_MAP_MARK, hasGeneratedMark, PROMPT_SNAPSHOT_MARK } from '../src/generated-mark.js';

describe('hasGeneratedMark', () => {
  it('finds the mark of each kind on the third line of the document its formatter writes, and not the mark of the other kind', () => {
    const flowMap = formatFlowMap('flow', { nodes: [], edges: [], phases: [], loops: [] });
    const promptSnapshot = formatPromptSnapshot('flow', []);

    assert.equal(hasGeneratedMark(flowMap, FLOW_MAP_MARK), true);
    assert.equal(hasGeneratedMark(flowMap, PROMPT_SNAPSHOT_MARK), false);
    assert.equal(hasGeneratedMark(promptSnapshot, PROMPT_SNAPSHOT_MARK), true);
    assert.equal(hasGeneratedMark(promptSnapshot, FLOW_MAP_MARK), false);
  });

  it('reads the third line with a CRLF line end, as a checkout that converts line ends writes it', () => {
    assert.equal(hasGeneratedMark(`# flow flow map\r\n\r\n${FLOW_MAP_MARK} Do not edit this file by hand.\r\n`, FLOW_MAP_MARK), true);
  });

  it('finds no mark in an empty text, a text of fewer than three lines, or a text that holds the mark on another line', () => {
    assert.equal(hasGeneratedMark('', FLOW_MAP_MARK), false);
    assert.equal(hasGeneratedMark(`${FLOW_MAP_MARK}\n`, FLOW_MAP_MARK), false);
    assert.equal(hasGeneratedMark(`# readme\n\nA flow map starts:\n\n${FLOW_MAP_MARK} Do not edit this file by hand.\n`, FLOW_MAP_MARK), false);
    assert.equal(hasGeneratedMark(`# notes\n\nSee ${FLOW_MAP_MARK}\n`, FLOW_MAP_MARK), false);
  });
});
