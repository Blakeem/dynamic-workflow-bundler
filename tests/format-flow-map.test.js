import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { join } from 'node:path';
import { describe, it } from 'node:test';
import { fileURLToPath } from 'node:url';
import { formatFlowMap } from '../src/format-flow-map.js';
import { map } from '../src/map.js';
import { sliceMarkdownSection } from './support/slice-markdown-section.js';

const ORACLE_FOLDER = fileURLToPath(new URL('./fixtures/flow-map/', import.meta.url));
const REFERENCE_SOURCES = { derived: 'returned', declared: 'scenario' };
const DIAGRAM_PATTERN = /^```mermaid\n[^]*?\n```$/m;
const HEAD = [
  '',
  'Generated by `dwfb map`. Do not edit this file by hand.',
  'Each node and edge below was reached by a scenario, so the diagram shows what the script does in a simulation.',
  '',
  '```mermaid',
  '%%{init: {"flowchart": {"nodeSpacing": 80, "rankSpacing": 200}}}%%',
  'flowchart TD',
  '  S0(["args"])',
];

/**
 * @param {Partial<import('../src/build-flow-graph.js').AgentNode>} fields
 * @returns {import('../src/build-flow-graph.js').AgentNode}
 */
function agentNode(fields) {
  const role = fields.role ?? 'work';
  return { id: 'a1', kind: 'agent', label: role, role, phase: '', model: '', concurrency: 1, ...fields };
}

/**
 * @param {Partial<import('../src/build-flow-graph.js').EndNode>} fields
 * @returns {import('../src/build-flow-graph.js').EndNode}
 */
function endNode(fields) {
  return { id: 't1', kind: 'end', label: 'done', source: 'returned', line: null, scenarios: ['s'], whens: ['s'], ...fields };
}

/**
 * @param {Partial<import('../src/build-flow-graph.js').FlowEdge>} fields
 * @returns {import('../src/build-flow-graph.js').FlowEdge}
 */
function edge(fields) {
  return { from: 'S0', to: 'a1', whens: ['s'], back: false, nextItem: false, repeat: 0, ...fields };
}

/**
 * @param {string} document
 * @returns {string[]} The lines of the diagram between the start node line and the closing fence.
 */
function readDiagramBody(document) {
  const lines = /** @type {RegExpExecArray} */ (DIAGRAM_PATTERN.exec(document))[0].split('\n');
  return lines.slice(HEAD.length - 4, -1);
}

/**
 * @param {string} section
 * @returns {string[]} The rows of the section's table, with no header and no divider.
 */
function readTableRows(section) {
  return section.split('\n').filter((line) => line.startsWith('|')).slice(2);
}

describe('formatFlowMap', () => {
  for (const name of ['seq', 'fan', 'rounds']) {
    it(`gives the diagram and the sections of the reference document for the oracle script ${name}`, async () => {
      const { graph } = await map({ script: join(ORACLE_FOLDER, `${name}.js`), scenarios: join(ORACLE_FOLDER, `${name}.scenarios.js`) });
      const reference = await readFile(join(ORACLE_FOLDER, `${name}.flow-map.md`), 'utf8');
      const document = formatFlowMap(name, /** @type {import('../src/build-flow-graph.js').FlowGraph} */ (graph));
      const referenceRows = readTableRows(sliceMarkdownSection(reference, '\n## Terminal states\n')).map((row) => row.replace(/\| (derived|declared) \|$/, (_, source) => `| ${REFERENCE_SOURCES[source]} |`));

      assert.ok(document.startsWith(`# ${name} flow map\n`));
      assert.equal(DIAGRAM_PATTERN.exec(document)?.[0], DIAGRAM_PATTERN.exec(reference)?.[0]);
      assert.equal(sliceMarkdownSection(document, '\n## Phases\n'), sliceMarkdownSection(reference, '\n## Phases\n'));
      for (const heading of ['\n## Loops\n', '\n## Edges\n']) {
        assert.equal(document.includes(heading), reference.includes(heading), heading);
      }
      if (reference.includes('\n## Loops\n')) assert.equal(sliceMarkdownSection(document, '\n## Loops\n'), sliceMarkdownSection(reference, '\n## Loops\n'));
      if (reference.includes('\n## Edges\n')) {
        const [documentEdges, referenceEdges] = [document, reference].map((text) => sliceMarkdownSection(text, '\n## Edges\n').trimEnd().split('\n').slice(0, -1));
        assert.deepEqual(documentEdges, referenceEdges);
      }
      assert.deepEqual(readTableRows(sliceMarkdownSection(document, '\n## End states\n')), referenceRows);
    });
  }

  it('writes a graph with no phase, no loop and no marked edge, with an empty phase table and one line end at the end', () => {
    const graph = {
      nodes: [agentNode({}), endNode({ source: 'scenario', whens: ['it ends', 'it ends early'] })],
      edges: [edge({}), edge({ from: 'a1', to: 't1' })],
      phases: [],
      loops: [],
    };

    assert.equal(
      formatFlowMap('plain', graph),
      [
        '# plain flow map',
        ...HEAD,
        '  a1["work"]',
        '  t1(["done"])',
        '  S0 --> a1',
        '  a1 --> t1',
        '```',
        '',
        '## Phases',
        '',
        '| Phase | What happens |',
        '|---|---|',
        '',
        '## End states',
        '',
        '| End state | Reached when | Source |',
        '|---|---|---|',
        '| done | it ends · it ends early | scenario |',
        '',
      ].join('\n'),
    );
  });

  it('escapes # ` & " | < and > in the diagram, the backslash, the inline marks and & | < and > in a table cell and in the title, and folds each run of white space', () => {
    const role = 'say"hi|<x>#lt;&amp;';
    const graph = {
      nodes: [
        agentNode({ role, label: role, phase: 'Plan "a"|<b>', model: 'big\tmodel' }),
        endNode({ label: '`done | "x"  <y>', whens: ['when | <z>\n&amp; `x` *y*_\\[z]~'] }),
        endNode({ id: 'x1', kind: 'throw', label: 'throw: Bad "a" | <b>', source: 'throw', line: 9, whens: ['it | throws'] }),
        agentNode({ id: 'a2', role: 'check' }),
      ],
      edges: [edge({}), edge({ from: 'a1', to: 't1' }), edge({ from: 'a1', to: 'x1' }), edge({ from: 'a1', to: 'a2' }), edge({ from: 'a2', to: 'a1', back: true, repeat: 1, whens: ['`agent()` <n> "left" | more #1;'] })],
      phases: [{ id: 'p1', title: 'Plan "a"|<b>', detail: 'Plans | <things>', nodes: ['a1'] }],
      loops: [],
    };
    const document = formatFlowMap('a|b <c>\n"d" &amp;', graph);

    assert.ok(document.startsWith('# a\\|b &lt;c&gt; "d" &amp;amp; flow map\n'));
    assert.deepEqual(readDiagramBody(document).slice(0, 3), [
      '  a1["say#quot;hi#124;#lt;x#gt;#35;lt;#38;amp; · big model<br/>Plan #quot;a#quot;#124;#lt;b#gt;"]',
      '  t1(["#96;done #124; #quot;x#quot; #lt;y#gt;"])',
      '  x1[/"throw: Bad #quot;a#quot; #124; #lt;b#gt;"/]',
    ]);
    assert.equal(readDiagramBody(document).at(-1), '  a2 -.->|"#96;agent()#96; #lt;n#gt; #quot;left#quot; #124; more #35;1;"| a1');
    assert.deepEqual(readTableRows(sliceMarkdownSection(document, '\n## Phases\n')), ['| Plan "a"\\|&lt;b&gt; | Plans \\| &lt;things&gt; |']);
    assert.deepEqual(readTableRows(sliceMarkdownSection(document, '\n## End states\n')), [
      '| \\`done \\| "x" &lt;y&gt; | when \\| &lt;z&gt; &amp;amp; \\`x\\` \\*y\\*\\_\\\\\\[z\\]\\~ | returned |',
      '| throw: Bad "a" \\| &lt;b&gt; | it \\| throws | throw (line 9) |',
    ]);
  });

  it('draws a phase of two or more nodes as a box, and the node of a one-node phase outside any box', () => {
    const graph = {
      nodes: [
        agentNode({ role: 'plan', phase: 'Plan' }),
        agentNode({ id: 'a2', role: 'draft', phase: 'Write "it"', concurrency: 3 }),
        agentNode({ id: 'a3', role: 'check', phase: 'Write "it"' }),
        endNode({}),
      ],
      edges: [edge({}), edge({ from: 'a1', to: 'a2' }), edge({ from: 'a2', to: 'a3' }), edge({ from: 'a3', to: 't1' })],
      phases: [
        { id: 'p1', title: 'Plan', detail: 'Plans.', nodes: ['a1'] },
        { id: 'p2', title: 'Write "it"', detail: 'Writes.', nodes: ['a2', 'a3'] },
        { id: 'p3', title: 'Unused', detail: 'Runs no call.', nodes: [] },
      ],
      loops: [],
    };
    const document = formatFlowMap('boxes', graph);

    assert.deepEqual(readDiagramBody(document).slice(0, 6), [
      '  subgraph p2["Write #quot;it#quot;"]',
      '    a2["draft<br/>Write #quot;it#quot;<br/>×3 concurrent"]',
      '    a3["check<br/>Write #quot;it#quot;"]',
      '  end',
      '  a1["plan"]',
      '  t1(["done"])',
    ]);
    assert.deepEqual(readTableRows(sliceMarkdownSection(document, '\n## Phases\n')), ['| Plan | Plans. |', '| Write "it" | Writes. |']);
  });

  it('cuts the conditions of a back edge caption to 70 characters with +<k> more, and keeps one condition whole', () => {
    const whens = ['a condition of twenty', 'b condition of twenty', 'c condition of twenty', 'd condition of twenty'];
    const longWhen = 'one condition that runs on past the seventy characters of an edge caption';
    const graph = {
      nodes: [agentNode({}), agentNode({ id: 'a2', role: 'check' }), agentNode({ id: 'a3', role: 'fix' }), endNode({})],
      edges: [
        edge({}),
        edge({ from: 'a1', to: 'a2' }),
        edge({ from: 'a2', to: 'a1', whens, back: true, repeat: 3 }),
        edge({ from: 'a2', to: 'a3' }),
        edge({ from: 'a3', to: 'a1', whens: [longWhen], back: true, repeat: 2 }),
        edge({ from: 'a3', to: 'a2', whens: whens.slice(0, 3), back: true, repeat: 1 }),
        edge({ from: 'a3', to: 't1' }),
      ],
      phases: [],
      loops: [],
    };
    const document = formatFlowMap('captions', graph);

    assert.ok(longWhen.length > 70);
    assert.deepEqual(
      readDiagramBody(document).filter((line) => line.includes('-.->')),
      [
        '  a2 -.->|"a condition of twenty · b condition of twenty · +2 more (×3)"| a1',
        `  a3 -.->|"${longWhen} (×2)"| a1`,
        '  a3 -.->|"a condition of twenty · b condition of twenty · c condition of twenty"| a2',
      ],
    );
    assert.equal(document.includes('\n## Loops\n') || document.includes('\n## Edges\n'), false);
  });

  it('marks a back edge to its own node as a loop, and a back edge that shares its pair with a next-item edge as an edge', () => {
    const graph = {
      nodes: [agentNode({}), agentNode({ id: 'a2', role: 'check' }), endNode({})],
      edges: [
        edge({}),
        edge({ from: 'a1', to: 'a1', whens: ['it retries'], back: true, repeat: 3 }),
        edge({ from: 'a1', to: 'a1', whens: ['the next item'], nextItem: true }),
        edge({ from: 'a1', to: 'a2' }),
        edge({ from: 'a2', to: 'a1', whens: ['a check | fails'], back: true, repeat: 2 }),
        edge({ from: 'a2', to: 'a1', whens: ['the next item'], nextItem: true }),
        edge({ from: 'a2', to: 't1' }),
      ],
      phases: [],
      loops: [],
    };
    const document = formatFlowMap('markers', graph);

    assert.deepEqual(readDiagramBody(document).slice(4, 9), ['  a1 -.->|"L1 ×3"| a1', '  a1 ==>|"next item"| a1', '  a1 --> a2', '  a2 -.->|"E1 ×2"| a1', '  a2 ==> a1']);
    assert.equal(sliceMarkdownSection(document, '\n## Loops\n'), '\n## Loops\n\n| Loop | Agent | Repeats while |\n|---|---|---|\n| L1 | work | it retries |\n');
    assert.equal(
      sliceMarkdownSection(document, '\n## Edges\n'),
      '\n## Edges\n\n| Edge | From | To | Taken when |\n|---|---|---|---|\n| E1 | check | work | a check \\| fails |\n\nThe thick edge with no caption of each pair above is the step to the next item.\n',
    );
  });
});
